import io
import zipfile
import uuid
from typing import Optional
from fastapi import APIRouter, Depends, HTTPException, Response
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from services.api.app.db.session import get_db
from services.api.app.models.project import Project
from services.api.app.models.test_suite import TestCase
from services.api.app.models.user import OrganizationMember
from services.api.app.services.codegen import PlaywrightCodeGenerator
from services.api.app.security.deps import get_current_organization_membership

router = APIRouter(tags=["Automation Lab"])

@router.get("/projects/{project_id}/automation/code")
async def get_project_automation_code(
    project_id: uuid.UUID,
    membership: OrganizationMember = Depends(get_current_organization_membership),
    db: AsyncSession = Depends(get_db)
):
    proj_res = await db.execute(
        select(Project).where(
            Project.id == project_id,
            Project.organization_id == membership.organization_id
        )
    )
    project = proj_res.scalar_one_or_none()
    if not project:
        raise HTTPException(status_code=404, detail="Project not found")

    cases_res = await db.execute(
        select(TestCase).where(TestCase.project_id == project_id).order_by(TestCase.code_identifier.asc())
    )
    test_cases = cases_res.scalars().all()

    code = PlaywrightCodeGenerator.generate_typescript(
        project_name=project.name,
        test_cases=test_cases,
        base_url=project.target_url
    )
    return {
        "project_id": str(project.id),
        "project_name": project.name,
        "language": "typescript",
        "runner": "@playwright/test",
        "total_test_cases": len(test_cases),
        "code": code
    }

@router.get("/projects/{project_id}/automation/export-package")
async def export_automation_package(
    project_id: uuid.UUID,
    membership: OrganizationMember = Depends(get_current_organization_membership),
    db: AsyncSession = Depends(get_db)
):
    proj_res = await db.execute(
        select(Project).where(
            Project.id == project_id,
            Project.organization_id == membership.organization_id
        )
    )
    project = proj_res.scalar_one_or_none()
    if not project:
        raise HTTPException(status_code=404, detail="Project not found")

    cases_res = await db.execute(
        select(TestCase).where(TestCase.project_id == project_id).order_by(TestCase.code_identifier.asc())
    )
    test_cases = cases_res.scalars().all()

    spec_code = PlaywrightCodeGenerator.generate_typescript(
        project_name=project.name,
        test_cases=test_cases,
        base_url=project.target_url
    )

    package_json = f"""{{
  "name": "qa-automation-{str(project.id)[:8]}",
  "version": "1.0.0",
  "description": "Exported Playwright test suite for {project.name}",
  "scripts": {{
    "test": "playwright test",
    "test:ui": "playwright test --ui",
    "report": "playwright show-report"
  }},
  "devDependencies": {{
    "@playwright/test": "^1.44.0",
    "typescript": "^5.4.0"
  }}
}}
"""

    playwright_config = f"""import {{ defineConfig, devices }} from '@playwright/test';

export default defineConfig({{
  testDir: './tests',
  fullyParallel: true,
  forbidOnly: !!process.env.CI,
  retries: process.env.CI ? 2 : 0,
  workers: process.env.CI ? 1 : undefined,
  reporter: 'html',
  use: {{
    baseURL: '{project.target_url}',
    trace: 'on-first-retry',
    screenshot: 'only-on-failure',
  }},
  projects: [
    {{
      name: 'chromium',
      use: {{ ...devices['Desktop Chrome'] }},
    }},
  ],
}});
"""

    readme_md = f"""# Automated Test Suite for {project.name}

Generated by **AI QA Agent Enterprise SaaS**.

## Prerequisites
- Node.js 18+

## Quickstart
```bash
npm install
npx playwright install --with-deps
npm test
```
"""

    # Build ZIP in-memory
    zip_buffer = io.BytesIO()
    with zipfile.ZipFile(zip_buffer, "w", zipfile.ZIP_DEFLATED) as zip_file:
        zip_file.writestr("package.json", package_json)
        zip_file.writestr("playwright.config.ts", playwright_config)
        zip_file.writestr("README.md", readme_md)
        zip_file.writestr("tests/app.spec.ts", spec_code)

    zip_buffer.seek(0)
    zip_bytes = zip_buffer.getvalue()

    filename = f"playwright-tests-{str(project.id)[:8]}.zip"
    return Response(
        content=zip_bytes,
        media_type="application/zip",
        headers={"Content-Disposition": f"attachment; filename={filename}"}
    )
